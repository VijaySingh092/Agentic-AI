import express from 'express'
import dotenv from 'dotenv'
dotenv.config()
import * as z from "zod"
import { ChatGoogle } from "@langchain/google";
import { Command, interrupt, StateGraph, StateSchema } from '@langchain/langgraph'
import { MongoClient } from "mongodb";
import { MongoDBSaver } from "@langchain/langgraph-checkpoint-mongodb";
import {randomUUID} from "node:crypto"


const app = express()

const port = process.env.PORT || 5000

app.use(express.json());

// checkpointer backed by database
const client = new MongoClient(process.env.MONGO_URI)
const checkpointer = new MongoDBSaver({ client });


 // set model
const model = new ChatGoogle("gemini-3.5-flash-lite")

// create custom state
const customState = new StateSchema({
    prompt:z.string(),
    approvalRequires:z.boolean(),
    aiResponse:z.string(),
    approved:z.boolean(),
    result:z.string()
})

// agentNode : calls model
const agent = async (state)=>{                
   const result = await model.invoke([
    {
        role:"system",
        content:`You are a helpful assisstant.
        If the user is greeting or asking a normal question, responsd normally and set approvalRequires to false.
        If the request requires a sensitive external action, such as sending an email or deleting a file, set approvalRequires to true. 
        Return JSON with: 
        {
        "response":"your response",
        "approvalRequires": true or false
        }`
    },
    {
        role:"user",
        content:state.prompt
    }
   ])

//    const parsed = JSON.parse(result.content)
let content = result.content.trim();

// Remove Markdown code fences if Gemini includes them
content = content.replace(/^```json\s*/i, "");
content = content.replace(/^```\s*/i, "");
content = content.replace(/\s*```$/i, "");

const parsed = JSON.parse(content);

    return {
        aiResponse:parsed.response,
        approvalRequires:parsed.approvalRequires
    }
}  

// approvalNode : interrupt() pauses the workflow and ask the human user for permission before performing a sensitive action
const approvalNode = async(state)=>{
    const answer = interrupt({
        message:"Do you approve this action",
        prompt:state.prompt,   // original message or request entered by the user
        aiResponse:state.aiResponse   // text generated by the AI after understanding the user's request. It is not necessarily the actual action or the content that will be sent.
    })
    return {
        approved:String(answer).trim().toLowerCase()==="yes"
    }
}

// action node
const actionNode  = async(state)=>{
    if(state.approved){
        return{
            result:`action approved`
        }
    }
    return {
        result:"action rejected by human"
    }
}

const shouldContinue= async(state)=>{
    if(state.approvalRequires){
        return "approval"
    } else{ 
        return "__end__"
    }
}


// create graph  with custom state
const graph = new StateGraph(customState)
.addNode("agent",agent)
.addNode("approval",approvalNode)
.addNode("action",actionNode)
.addEdge("__start__","agent")
.addConditionalEdges("agent",shouldContinue)   // After the agent node finishes executing, call the shouldContinue function
.addEdge("approval","action")
.addEdge("action","__end__")
.compile({checkpointer})


// Responsible for starting the graph. When the graph reaches interrupt(), it pauses and returns the interruption information.
app.post("/chat", async (req,res)=>{
    const {prompt} = req.body
    const threadId = randomUUID() // Generate a new thread ID, so no previous chat history or memory is retained.
    const result = await graph.invoke(
        {
            prompt
        },
    {
        configurable:{thread_id:threadId}
    }
    )
    return res.json({
        threadId,
        result:result.result,
        ai_response:result.aiResponse
    })
})

// Receives the user's approval or rejection and resumes the previously paused graph
app.post("/chat/resume", async (req,res)=>{
    const {threadId, answer} = req.body

    const result = await graph.invoke(
       new Command({         // Command({ resume: value }) provides the input and resumes the graph
        resume:String(answer)
       }),
        {
        configurable:{thread_id:threadId}
        }
    )
    return res.json({
        threadId,
        result:result.result
    })
})


app.listen(port,()=>{
    console.log(`Server is running on port : ${port}`)
})